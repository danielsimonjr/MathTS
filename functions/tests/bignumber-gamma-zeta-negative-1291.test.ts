describe('gamma of a non-integer BigNumber (#1291)', () => {
  it.each(GAMMA_20)('precision 20: gamma(%s)', { timeout: 20000 }, (s, expected) => {
    BigNumber.config({ precision: 20 });
    expect(call('gamma', s)).toBe(same(expected));
  });
  it.each(GAMMA_64)('precision 64: gamma(%s)', { timeout: 20000 }, (s, expected) => {
    BigNumber.config({ precision: 64 });
    expect(call('gamma', s)).toBe(same(expected));
  });
  it('gamma(1.5) remains available for fractional arguments', () => {
    BigNumber.config({ precision: 64 });
    expect(call('gamma', '1.5')).toBe(
      same('0.8862269254527580136490837416705725913987747280611935641069038949')
    );
  });
});

describe('gamma and factorial of a non-finite BigNumber (#1291)', () => {
  it('gamma(NaN) and factorial(NaN) are NaN', () => {
    expect(call('gamma', 'NaN')).toBe('NaN');
    expect(call('factorial', 'NaN')).toBe('NaN');
  });
  it('gamma(-Infinity) is NaN and gamma(Infinity) is Infinity', () => {
    expect(call('gamma', '-Infinity')).toBe('NaN');
    expect(call('gamma', 'Infinity')).toBe('Infinity');
  });
});

