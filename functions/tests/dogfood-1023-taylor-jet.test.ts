describe('#1023 taylor coefficients against SymPy and mpmath', () => {
  for (const [expr, x0, n, want] of ORACLE) {
    it(`${expr} at ${x0}, orders 0..${n}`, () => {
      for (let k = 0; k <= n; k++) {
        const got = seriesCoefficient(expr, 'x', x0, k);
        if (want[k] === 0) expect(got).toBe(0);
        else expect(Math.abs(got - want[k])).toBeLessThanOrEqual(1e-12 * Math.abs(want[k]));
      }
    });
  }

  it('x/(1-x-x^2) to order 10 prints the Fibonacci numbers', () => {
    expect(taylor('x/(1-x-x^2)', 'x', 0, 10)).toBe(
      'x + x^2 + 2*x^3 + 3*x^4 + 5*x^5 + 8*x^6 + 13*x^7 + 21*x^8 + 34*x^9 + 55*x^10'
    );
    expect(seriesCoefficient('x/(1-x-x^2)', 'x', 0, 8)).toBe(21);
  });

  it('1/(1-x) to order 30 has every coefficient 1', () => {
    const want = ['1', 'x', ...Array.from({ length: 29 }, (_, i) => `x^${i + 2}`)].join(' + ');
    expect(taylor('1/(1-x)', 'x', 0, 30)).toBe(want);
  });

  it('exp(x) to order 17 keeps the small true coefficients of x^15..x^17', () => {
    const text = taylor('exp(x)', 'x', 0, 17);
    expect(text).toContain('7.647163732e-13*x^15');
    expect(text).toContain('4.779477332e-14*x^16');
    expect(text).toContain('2.811457254e-15*x^17');
  });

  it('a rounding-noise coefficient is left out (sin(x) at pi)', () => {
    expect(taylor('sin(x)', 'x', Math.PI, 3)).toBe(
      '-(x - 3.141592654) + 0.1666666667*(x - 3.141592654)^3'
    );
  });

  it('tan(x) to order 15 (a high order only the jet tier reaches) is exact', () => {
    // Deterministic proxy for the speed of #1023: the symbolic pass stops at order 24 and the
    // old aliasing contour gave a wrong x^15; the jet tier gives 929569/638512875.
    const c = seriesCoefficient('tan(x)', 'x', 0, 15);
    expect(Math.abs(c - 929569 / 638512875)).toBeLessThanOrEqual(1e-12 * c);
  });
});
