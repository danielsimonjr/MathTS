/**
 * Mathieu-function oracle test: characteristic values a_n(q)/b_n(q) and the
 * angular functions ce_n(x,q)/se_n(x,q).
 *
 * Ground truth: `scipy.special` (mathieu_a / mathieu_b / mathieu_cem /
 * mathieu_sem). The installed `mpmath` 1.3.0 does not ship the Mathieu family;
 * scipy uses the identical DLMF normalization (verified: mathieu_cem(0,0,0) =
 * 1/√2). scipy takes the angle in DEGREES — the constants below are already
 * converted to radians. Regenerate with the maintainer's scratchpad
 * `gen_oracle.py`.
 */

function relerr(actual: number, expected: number): number {
  if (expected === 0) return Math.abs(actual);
  return Math.abs((actual - expected) / expected);
}

