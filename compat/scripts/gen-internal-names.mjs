// Writes compat/src/internal-names.generated.ts: the internal names of the functions
// namespace, sorted (#1216). compat `create` does not surface these names, the
// expression scope of a compat instance does not resolve them, and the `MathInstance`
// type omits them. An internal name has the shape `factory_<name>` or ALL_CAPS. The
// mathjs-parity names (`LN2`, `SQRT1_2`, ...) and the names in KEEP are API.
// The script imports the built functions package: run `bunx turbo build` first.
// Run: node compat/scripts/gen-internal-names.mjs [--check]
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { isEntryPoint, runGenerator } from './generated-file.mjs';
import { mathjsParityNames } from './gen-parity-names.mjs';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const COMPAT_DIR = resolve(dirname(SCRIPT_PATH), '..');
const OUTPUT_PATH = resolve(COMPAT_DIR, 'src/internal-names.generated.ts');

/** The shape of an internal name: `factory_*` or ALL_CAPS. */
const INTERNAL_NAME_SHAPE = /^(?:factory_|[A-Z][A-Z0-9_]*$)/;

/**
 * Names with the internal shape that are API of the compat instance.
 * `EARTH_RADIUS_KM` is the default radius of `haversine`, a physical constant.
 */
const KEEP = new Set(['EARTH_RADIUS_KM']);

/**
 * Renders the generated module from the built functions package.
 *
 * @returns {Promise<string>} The file text.
 */
export async function generate() {
  const require = createRequire(resolve(COMPAT_DIR, 'package.json'));
  const entry = require.resolve('@danielsimonjr/mathts-functions');
  const functions = await import(pathToFileURL(entry).href);
  const parity = new Set(mathjsParityNames().names);
  const names = Object.keys(functions)
    .filter((key) => INTERNAL_NAME_SHAPE.test(key) && !parity.has(key) && !KEEP.has(key))
    .sort();
  if (names.length === 0) {
    throw new Error('No internal names found in ' + entry + '. Build the functions package.');
  }
  const lines = [
    '// This file is generated by compat/scripts/gen-internal-names.mjs. Do not edit it.',
    '/**',
    ' * The internal names of the functions namespace (#1216), sorted: the `factory_*`',
    ' * functions and the ALL_CAPS tuning constants that are not mathjs names.',
    ' * compat `create` does not surface them, and `MathInstance` omits them.',
    ' * They stay exported from `@danielsimonjr/mathts-functions`.',
    ' *',
    ' * @packageDocumentation',
    ' */',
    '',
    '/** The internal names of the functions namespace. */',
    'export const COMPAT_INTERNAL_NAMES = [',
    ...names.map((name) => `  ${JSON.stringify(name)},`),
    '] as const;',
    '',
    '/** One internal name of the functions namespace. */',
    'export type CompatInternalName = (typeof COMPAT_INTERNAL_NAMES)[number];',
    '',
  ];
  return lines.join('\n');
}

if (isEntryPoint(SCRIPT_PATH)) {
  await runGenerator(OUTPUT_PATH, generate, 'gen-internal-names.mjs');
}
