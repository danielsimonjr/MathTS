// Writes compat/src/parity-names.generated.ts: the own keys of the mathjs instance
// `create(all)` of the mathjs devDependency, sorted. compat `create` keeps exactly the
// names of this list that it surfaces as own keys of the instance (#1200); every other
// name goes on a prototype level. mathjs is not a runtime dependency of compat, so the
// list is committed. Run: node compat/scripts/gen-parity-names.mjs [--check]
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isEntryPoint, runGenerator } from './generated-file.mjs';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const COMPAT_DIR = resolve(dirname(SCRIPT_PATH), '..');
const OUTPUT_PATH = resolve(COMPAT_DIR, 'src/parity-names.generated.ts');

/**
 * Reads the own keys of the instance `create(all)` of the installed mathjs.
 *
 * @returns The sorted names and the mathjs version.
 */
export function mathjsParityNames() {
  const require = createRequire(resolve(COMPAT_DIR, 'package.json'));
  const mathjs = require('mathjs');
  const version = require('mathjs/package.json').version;
  return { names: Object.keys(mathjs.create(mathjs.all)).sort(), version };
}

/**
 * Renders the generated module from the installed mathjs.
 *
 * @returns The file text.
 */
export function generate() {
  const { names, version } = mathjsParityNames();
  const lines = [
    '// This file is generated by compat/scripts/gen-parity-names.mjs. Do not edit it.',
    '/**',
    ` * The own keys of the mathjs ${version} instance \`create(all)\`, sorted.`,
    ' * compat `create` keeps the names of this list as own keys of the instance.',
    ' *',
    ' * @packageDocumentation',
    ' */',
    '',
    '/** The own keys of the mathjs instance `create(all)`. */',
    'export const MATHJS_PARITY_NAMES: readonly string[] = [',
    ...names.map((name) => `  ${JSON.stringify(name)},`),
    '];',
    '',
  ];
  return lines.join('\n');
}

if (isEntryPoint(SCRIPT_PATH)) {
  await runGenerator(OUTPUT_PATH, generate, 'gen-parity-names.mjs');
}
