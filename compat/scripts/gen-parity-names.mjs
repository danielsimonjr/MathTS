// Writes compat/src/parity-names.generated.ts: the own keys of the mathjs instance
// `create(all)` of the mathjs devDependency, sorted. compat `create` keeps exactly the
// names of this list that it surfaces as own keys of the instance (#1200); every other
// name goes on a prototype level. mathjs is not a runtime dependency of compat, so the
// list is committed. Run: node compat/scripts/gen-parity-names.mjs [--check]
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { isEntryPoint, runGenerator } from './generated-file.mjs';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const COMPAT_DIR = resolve(dirname(SCRIPT_PATH), '..');
const OUTPUT_PATH = resolve(COMPAT_DIR, 'src/parity-names.generated.ts');
const PHYSICAL_EXPORTS_PATH = resolve(COMPAT_DIR, 'src/named-physical-constants.generated.ts');
const SCALAR_PHYSICAL_NAMES = ['efimovFactor', 'fineStructure', 'sackurTetrode', 'weakMixingAngle'];

/**
 * Reads the own keys of the instance `create(all)` of the installed mathjs.
 *
 * @returns The sorted names and the mathjs version.
 */
export function mathjsParityNames() {
  const require = createRequire(resolve(COMPAT_DIR, 'package.json'));
  const mathjs = require('mathjs');
  const version = require('mathjs/package.json').version;
  const instance = mathjs.create(mathjs.all);
  const precise = mathjs.create(mathjs.all, { number: 'BigNumber', precision: 128 });
  const names = Object.keys(instance).sort();
  const unitConstants = names.flatMap((name) => {
    const value = instance[name];
    if (!instance.isUnit(value)) return [];
    const units = value.formatUnits();
    const magnitude = value.toNumeric(units);
    const decimal = precise[name].toNumeric(units).toString();
    return [[name, magnitude, units, decimal === String(magnitude) ? null : decimal]];
  });
  const scalarConstants = SCALAR_PHYSICAL_NAMES.map((name) => [name, mathjs[name]]);
  return { names, version, unitConstants, scalarConstants };
}

/**
 * Renders the generated module from the installed mathjs.
 *
 * @returns The file text.
 */
export function generate() {
  const { names, version, unitConstants } = mathjsParityNames();
  const lines = [
    '// This file is generated by compat/scripts/gen-parity-names.mjs. Do not edit it.',
    '/**',
    ` * The own keys of the mathjs ${version} instance \`create(all)\`, sorted.`,
    ' * compat `create` keeps the names of this list as own keys of the instance.',
    ' *',
    ' * @packageDocumentation',
    ' */',
    '',
    '/** The own keys of the mathjs instance `create(all)`. */',
    'export const MATHJS_PARITY_NAMES: readonly string[] = [',
    ...names.map((name) => `  ${JSON.stringify(name)},`),
    '];',
    '',
    '/** The version-pinned mathjs physical constants, expressed in their display units. */',
    'export const MATHJS_UNIT_CONSTANTS = [',
    ...unitConstants.map((entry) => `  ${JSON.stringify(entry)},`),
    '] as const;',
    '',
  ];
  return lines.join('\n');
}

/**
 * Render direct imports for the constants also available on the MathJS module.
 *
 * @returns The generated TypeScript module.
 */
export async function generatePhysicalExports() {
  const { unitConstants, scalarConstants, version } = mathjsParityNames();
  const localName = (name) => 'mathjs' + name[0].toUpperCase() + name.slice(1);
  const source = [
    '// This file is generated by compat/scripts/gen-parity-names.mjs. Do not edit it.',
    "import { Unit, type UnitInstance } from '@danielsimonjr/mathts-core';",
    "import { MATHJS_UNIT_CONSTANTS } from './parity-names.generated.js';",
    '',
    'function createUnitConstant([, value, units]: (typeof MATHJS_UNIT_CONSTANTS)[number]): UnitInstance {',
    '  const unit = new Unit(value, units);',
    '  unit.fixPrefix = true;',
    '  return unit;',
    '}',
    '',
    ...unitConstants.flatMap(([name, , units], index) => [
      `/** MathJS ${version} value of ${name}, expressed in ${units}. */`,
      `const ${localName(name)}: UnitInstance = /* #__PURE__ */ createUnitConstant(MATHJS_UNIT_CONSTANTS[${index}]);`,
    ]),
    '',
    ...scalarConstants.flatMap(([name, value]) => [
      `/** MathJS ${version} value of the dimensionless constant ${name}. */`,
      `const ${localName(name)} = ${JSON.stringify(value)};`,
    ]),
    '',
    'export {',
    ...[...unitConstants, ...scalarConstants].map(([name]) => `  ${localName(name)} as ${name},`),
    '};',
    '',
  ].join('\n');
  return format(source, {
    ...(await resolveConfig(PHYSICAL_EXPORTS_PATH)),
    filepath: PHYSICAL_EXPORTS_PATH,
  });
}

if (isEntryPoint(SCRIPT_PATH)) {
  await runGenerator(OUTPUT_PATH, generate, 'gen-parity-names.mjs');
  await runGenerator(PHYSICAL_EXPORTS_PATH, generatePhysicalExports, 'gen-parity-names.mjs');
}
