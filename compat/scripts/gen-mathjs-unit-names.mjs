// Writes compat/src/mathjs-unit-names.generated.ts: mathjs 15.3.0 `Unit.UNITS`
// keys plus the prefix *group* each unit uses. Prefixed valueless forms are
// derived at runtime; this is not a cartesian product of every prefix×unit.
// mathjs is not a runtime dependency of compat, so the data is committed.
// Run: node compat/scripts/gen-mathjs-unit-names.mjs [--check]
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isEntryPoint, runGenerator } from './generated-file.mjs';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const COMPAT_DIR = resolve(dirname(SCRIPT_PATH), '..');
const OUTPUT_PATH = resolve(COMPAT_DIR, 'src/mathjs-unit-names.generated.ts');

/**
 * Read mathjs 15.3.0 unit names and prefix-group membership.
 * @returns Unit metadata from the installed mathjs devDependency.
 */
export function mathjsUnitSurface() {
  const require = createRequire(resolve(COMPAT_DIR, 'package.json'));
  const mathjs = require('mathjs');
  const version = require('mathjs/package.json').version;
  const instance = mathjs.create(mathjs.all);
  const unitNames = Object.keys(instance.Unit.UNITS).sort();
  const groupByRef = new Map();
  const groups = {};
  for (const [groupName, group] of Object.entries(instance.Unit.PREFIXES)) {
    if (group === null || typeof group !== 'object') continue;
    groupByRef.set(group, groupName);
    groups[groupName] = Object.keys(group)
      .filter((key) => key.length > 0)
      .sort();
  }
  const unitPrefixGroup = {};
  const extraGroups = {};
  for (const name of unitNames) {
    const prefixes = instance.Unit.UNITS[name].prefixes;
    const known = groupByRef.get(prefixes);
    if (typeof known === 'string') {
      unitPrefixGroup[name] = known;
      continue;
    }
    const extraName = `custom:${name}`;
    extraGroups[extraName] = Object.keys(prefixes)
      .filter((key) => key.length > 0)
      .sort();
    unitPrefixGroup[name] = extraName;
  }
  return { version, unitNames, groups: { ...groups, ...extraGroups }, unitPrefixGroup };
}

/**
 * Render `compat/src/mathjs-unit-names.generated.ts`.
 * @returns Generated TypeScript module text.
 */
export function generate() {
  const { version, unitNames, groups, unitPrefixGroup } = mathjsUnitSurface();
  const groupLines = Object.keys(groups)
    .sort()
    .flatMap((groupName) => [
      `  ${JSON.stringify(groupName)}: [`,
      ...groups[groupName].map((prefix) => `    ${JSON.stringify(prefix)},`),
      '  ],',
    ]);
  const unitGroupLines = unitNames.map(
    (name) => `  ${JSON.stringify(name)}: ${JSON.stringify(unitPrefixGroup[name])},`
  );
  const lines = [
    '// This file is generated by compat/scripts/gen-mathjs-unit-names.mjs. Do not edit it.',
    '/**',
    ` * mathjs ${version} \`Unit.UNITS\` keys and prefix groups, pinned for`,
    ' * compat `toTex` (#1577). Prefixed valueless names are derived at runtime.',
    ' *',
    ' * @packageDocumentation',
    ' */',
    '',
    `/** Sorted \`Unit.UNITS\` keys from mathjs ${version} \`create(all)\`. */`,
    'export const MATHJS_UNIT_NAMES: readonly string[] = [',
    ...unitNames.map((name) => `  ${JSON.stringify(name)},`),
    '];',
    '',
    `/** Prefix names per mathjs ${version} \`Unit.PREFIXES\` group (non-empty keys). */`,
    'export const MATHJS_PREFIX_GROUPS: Readonly<Record<string, readonly string[]>> = {',
    ...groupLines,
    '};',
    '',
    `/** \`Unit.UNITS[name].prefixes\` group for each mathjs ${version} unit. */`,
    'export const MATHJS_UNIT_PREFIX_GROUP: Readonly<Record<string, string>> = {',
    ...unitGroupLines,
    '};',
    '',
  ];
  return lines.join('\n');
}

if (isEntryPoint(SCRIPT_PATH)) {
  await runGenerator(OUTPUT_PATH, generate, 'node compat/scripts/gen-mathjs-unit-names.mjs');
}
