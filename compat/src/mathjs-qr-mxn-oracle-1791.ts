export function fingerprintComplexMatrixData(data: unknown[][]): string {
  return data
    .map((row) =>
      row
        .map((cell) => {
          const z = cell as { re?: number; im?: number; type?: string };
          if (z && z.type === 'Complex' && typeof z.re === 'number' && typeof z.im === 'number') {
            return `${z.re},${z.im}`;
          }
          return String(cell);
        })
        .join(';')
    )
    .join('|');
}
